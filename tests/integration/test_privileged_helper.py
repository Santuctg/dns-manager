def test_validate_refuses_staged_symlinks_and_does_not_echo_content(tmp_path):
    paths = make_paths(tmp_path)
    secret = tmp_path / "shadow"
    secret.write_text("root:$6$secret-hash:19000:0:99999:7:::\n")
    paths.staged_dnsmasq.symlink_to(secret)
    paths.staged_nginx.write_text(GOOD_NGINX)

    with pytest.raises(RuntimeError) as excinfo:
        HelperOps(paths=paths, runner=FakeRunner()).validate()
    assert "secret-hash" not in str(excinfo.value)

    # Swapping the real file in still never reflects its content in the error.
    paths.staged_dnsmasq.unlink()
    paths.staged_dnsmasq.write_text(secret.read_text())
    with pytest.raises(ValueError) as excinfo:
        HelperOps(paths=paths, runner=FakeRunner()).validate()
    assert "secret-hash" not in str(excinfo.value)


def test_validate_refuses_oversized_and_non_regular_staged_files(tmp_path):
    paths = make_paths(tmp_path)
    paths.staged_dnsmasq.write_text("#" * (4 * 1024 * 1024 + 1))
    paths.staged_nginx.write_text(GOOD_NGINX)
