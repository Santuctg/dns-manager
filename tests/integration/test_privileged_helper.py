class Result:
    def __init__(self, returncode=0, stdout="", stderr=""):
        self.returncode = returncode
        self.stdout = stdout
        self.stderr = stderr


class FakeRunner:
    def __init__(self, responses=None):
        self.calls = []
        self.responses = list(responses or [])

    def __call__(self, argv, **kwargs):
        self.calls.append(list(argv))
        if self.responses:
            return self.responses.pop(0)
        return Result()


GOOD_DNS = "# AUTO-GENERATED BY DNS MANAGER\n\naddress=/app.example.com/192.168.8.10\n"
GOOD_NGINX = """# AUTO-GENERATED BY DNS MANAGER
server {
    listen 80;
    server_name app.example.com;

    location / {
        proxy_pass http://10.0.0.5:8080;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";

        proxy_connect_timeout 15s;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
    }
}
"""


def make_paths(tmp_path: Path) -> HelperPaths:
    generated = tmp_path / "generated"
    live_dns_dir = tmp_path / "etc" / "dnsmasq.d"
    live_nginx_dir = tmp_path / "etc" / "nginx" / "conf.d"
    for directory in (generated, live_dns_dir, live_nginx_dir):
        directory.mkdir(parents=True, exist_ok=True)
    return HelperPaths(
        staged_dnsmasq=generated / "dnsmasq.conf",
        staged_nginx=generated / "nginx.conf",
        live_dnsmasq=live_dns_dir / "dns-manager.conf",
        live_nginx=live_nginx_dir / "dns-manager.conf",
        private_dir=tmp_path / "helper" / "config",
    )


def stage(paths: HelperPaths, dns: str = GOOD_DNS, nginx: str = GOOD_NGINX) -> None:
    paths.staged_dnsmasq.write_text(dns)
    paths.staged_nginx.write_text(nginx)


def test_dispatch_rejects_unknown_command_and_extra_arguments(tmp_path):
    ops = HelperOps(paths=make_paths(tmp_path), runner=FakeRunner())

    assert dispatch(["shell"], ops) == 2
    assert dispatch(["validate", "/tmp/evil"], ops) == 2


def test_validate_tests_root_owned_copies_with_a_helper_written_main_config(tmp_path):
    paths = make_paths(tmp_path)
    stage(paths)
    # Anything the service writes as a main config is ignored.
    (paths.staged_nginx.parent / "nginx-test.conf").write_text("load_module /tmp/evil.so;\n")
    runner = FakeRunner()
    ops = HelperOps(paths=paths, runner=runner)

    assert dispatch(["validate"], ops) == 0
    assert runner.calls == [
        ["/usr/sbin/dnsmasq", "--test", f"--conf-file={paths.candidate_dnsmasq}"],
        [
            "/usr/sbin/nginx",
            "-t",
            "-c",
            str(paths.candidate_nginx_main),
            "-g",
            f"pid {paths.candidate_dir / 'nginx-test.pid'};",
        ],
    ]
    main = paths.candidate_nginx_main.read_text()
    assert "load_module" not in main
    assert f"include {paths.candidate_nginx};" in main
    assert str(paths.staged_nginx.parent) not in main
    assert paths.candidate_dnsmasq.read_text() == GOOD_DNS
    assert paths.candidate_nginx.read_text() == GOOD_NGINX


def test_renderer_output_passes_the_helper_content_checks():
    from types import SimpleNamespace

    from app.services.dns_service import render_dnsmasq_config
    from app.services.nginx_service import render_nginx_config
    from privileged.helper_lib import validate_dnsmasq_text, validate_nginx_text

    def mapping(domain, host, **kw):
        base = dict(domain=domain, upstream_scheme="http", upstream_host=host, upstream_port=8080,
                    enabled=True, websocket_enabled=True, preserve_host=True, custom_timeout=None)
        return SimpleNamespace(**{**base, **kw})

    mappings = [
        mapping("a.example.com", "10.0.0.5"),
        mapping("b.example.com", "fd00::1", upstream_scheme="https", upstream_port=443,
                websocket_enabled=False, preserve_host=False, custom_timeout=3600),
        mapping("c.example.com", "backend.internal"),
        mapping("d.example.com", "localhost", enabled=False),
    ]
    validate_dnsmasq_text(render_dnsmasq_config(mappings, "192.168.8.10"))
    validate_dnsmasq_text(render_dnsmasq_config(mappings, "fd00::53"))
    validate_dnsmasq_text(render_dnsmasq_config([], "192.168.8.10"))
    validate_nginx_text(render_nginx_config(mappings))
    validate_nginx_text(render_nginx_config([]))


