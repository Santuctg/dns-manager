import pytest

from app.models.mapping import Mapping
from app.services.dns_service import render_dnsmasq_config


def mapping(domain: str, *, enabled: bool = True) -> Mapping:
    return Mapping(
        domain=domain,
        upstream_scheme="http",
        upstream_host="192.168.8.2",
        upstream_port=8082,
        enabled=enabled,
    )


def test_enabled_mappings_render_split_dns_records_in_sorted_order():
    rendered = render_dnsmasq_config(
        [mapping("z.example.com"), mapping("a.example.com")],
        "192.168.8.10",
    )

    assert rendered.index("address=/a.example.com/192.168.8.10") < rendered.index(
        "address=/z.example.com/192.168.8.10"
    )


def test_disabled_mapping_is_omitted():
    rendered = render_dnsmasq_config(
        [mapping("enabled.example.com"), mapping("disabled.example.com", enabled=False)],
        "192.168.8.10",
    )

    assert "address=/enabled.example.com/192.168.8.10" in rendered
    assert "disabled.example.com" not in rendered


def test_output_has_generated_warning_and_only_managed_records():
    rendered = render_dnsmasq_config([mapping("panel.example.com")], "192.168.8.10")

    assert "AUTO-GENERATED BY DNS MANAGER" in rendered
    assert "DO NOT EDIT MANUALLY" in rendered
    assert "server=" not in rendered
    assert "resolv-file=" not in rendered
    assert "interface=" not in rendered


@pytest.mark.parametrize(
    "bad_domain",
    [
        "panel.example.com\nserver=1.1.1.1",
        "panel.example.com\raddress=/evil/1.2.3.4",
        "panel.example.com;server=8.8.8.8",
        "panel.example.com/address=/evil/1.2.3.4",
    ],
)
def test_unsafe_domain_cannot_be_rendered(bad_domain: str):
    with pytest.raises(ValueError, match="invalid domain"):
        render_dnsmasq_config([mapping(bad_domain)], "192.168.8.10")


def test_invalid_internal_proxy_ip_is_rejected():
    with pytest.raises(ValueError, match="invalid internal proxy IP"):
        render_dnsmasq_config([mapping("panel.example.com")], "192.168.8.10\nserver=1.1.1.1")
